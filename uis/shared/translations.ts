export function translate(language: Language, text: string, values: Record<string, string | number> = {}): string {
  const key = text.trim();
  const operationError = /^No se pudo completar la operación \(HTTP (\d+)\)\.$/.exec(key);
  if (operationError) return translate(language, "No se pudo completar la operación (HTTP {status}).", { status: operationError[1] });
  const translated = language === "en" && english[key] ? text.replace(key, () => english[key]) : text;
  return translated.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}